window.t = function(k, p){
    let s = (D[LANG] && D[LANG][k]) || k;
    if(p) for(const x in p) s = s.split("{" + x + "}").join(p[x]);
    return s;
};
window.traducirDOM = function(root){
    const dic = D[LANG];
    if(!dic) return;
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let n;
    while((n = w.nextNode())){
        if(n.parentNode && /^(SCRIPT|STYLE)$/.test(n.parentNode.nodeName)) continue;
        const k = n.nodeValue.trim();
        if(k && dic[k]) n.nodeValue = n.nodeValue.replace(k, () => dic[k]);
    }
    root.querySelectorAll("[placeholder],[aria-label],[title]").forEach(el => {
        ["placeholder", "aria-label", "title"].forEach(a => {
            const v = el.getAttribute(a);
            if(v && dic[v]) el.setAttribute(a, dic[v]);
        });
    });
};
document.documentElement.lang = LANG;
