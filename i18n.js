const SUP = ["es"].concat(Object.keys(D));
function elegir(){
    let q = null, g = null;
    try{ q = new URLSearchParams(location.search).get("lang"); g = localStorage.getItem("lang"); }catch(e){}
    const lista = [q, g].concat(navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "es"]).filter(Boolean);
    for(const tag of lista){
        const base = String(tag).toLowerCase().split("-")[0];
        if(SUP.indexOf(base) >= 0) return {base: base, tag: tag};
    }
    return {base: "en", tag: "en"};
}
const L = elegir();
